# Makes a second copy of the game for one-PC testing (the guest), with its own saves folder.
param(
    [string]$Root  = 'C:\Program Files (x86)\Steam\steamapps\common\SurrounDead',
    [string]$Guest = 'C:\Program Files (x86)\Steam\steamapps\common\SurrounDead_Guest',
    [switch]$ReseedSaves
)
$ErrorActionPreference = 'Stop'

$Repo      = Split-Path $PSScriptRoot -Parent
$ModSrc    = Join-Path $Repo 'mod\SurrounSync'
$SrcWin64  = Join-Path $Root  'SurrounDead\Binaries\Win64'
$DstWin64  = Join-Path $Guest 'SurrounDead\Binaries\Win64'

if (-not (Test-Path $SrcWin64)) { throw "Game not found at $Root" }

function Junction($path, $target) {
    if (Test-Path $path) {
        $item = Get-Item $path -Force
        if ($item.LinkType -eq 'Junction') { return }
        throw "$path exists and is not a junction - remove it manually (won't touch it)."
    }
    New-Item -ItemType Junction -Path $path -Target $target | Out-Null
    Write-Host "junction $path -> $target"
}

New-Item -ItemType Directory -Force (Join-Path $Guest 'SurrounDead') | Out-Null
New-Item -ItemType Directory -Force $DstWin64 | Out-Null
Junction (Join-Path $Guest 'Engine') (Join-Path $Root 'Engine')
Junction (Join-Path $Guest 'SurrounDead\Content') (Join-Path $Root 'SurrounDead\Content')

$files = @('SurrounDead-Win64-Shipping.exe', 'steam_appid.txt', 'dwmapi.dll', 'tbb12.dll', 'tbbmalloc.dll',
           'amd_fidelityfx_framegeneration_dx12.dll', 'amd_fidelityfx_upscaler_dx12.dll')
foreach ($f in $files) {
    $src = Join-Path $SrcWin64 $f
    if (Test-Path $src) { Copy-Item $src $DstWin64 -Force }
}
foreach ($d in 'D3D12', 'DML') { Copy-Item (Join-Path $SrcWin64 $d) $DstWin64 -Recurse -Force }

$SrcUe = Join-Path $SrcWin64 'ue4ss'
$DstUe = Join-Path $DstWin64 'ue4ss'
$DstMods = Join-Path $DstUe 'Mods'
New-Item -ItemType Directory -Force $DstMods | Out-Null
Copy-Item (Join-Path $SrcUe 'UE4SS.dll') $DstUe -Force
Copy-Item (Join-Path $SrcUe 'UE4SS-settings.ini') $DstUe -Force
Copy-Item (Join-Path $SrcUe 'UE4SS_Signatures') $DstUe -Recurse -Force
$mods = 'shared', 'Keybinds', 'BPModLoaderMod', 'BPML_GenericFunctions', 'ConsoleEnablerMod', 'ConsoleCommandsMod'
foreach ($m in $mods) { Copy-Item (Join-Path $SrcUe "Mods\$m") $DstMods -Recurse -Force }
Junction (Join-Path $DstMods 'SurrounSync') $ModSrc

$enabled = @('CheatManagerEnablerMod:0', 'ConsoleCommandsMod:1', 'ConsoleEnablerMod:1', 'BPML_GenericFunctions:1',
             'BPModLoaderMod:1', 'Keybinds:1', 'SurrounSync:1')

$HostPds = Join-Path $SrcUe 'Mods\PDS'
if (Test-Path $HostPds) {
    $item = Get-Item $HostPds -Force
    $target = if ($item.LinkType) { @($item.Target)[0] } else { $HostPds }
    Junction (Join-Path $DstMods 'PDS') $target
    $enabled += 'PDS:1'
}
$txt = @('; Guest install (SurrounSync dev). Generated by tools\setup-guest.ps1.')
$json = @()
foreach ($e in $enabled) {
    $n, $v = $e.Split(':')
    $txt += "$n : $v"
    $json += "    { `"mod_name`": `"$n`", `"mod_enabled`": $(if ($v -eq '1') { 'true' } else { 'false' }) }"
}
[IO.File]::WriteAllText((Join-Path $DstMods 'mods.txt'), ($txt -join "`r`n") + "`r`n")
[IO.File]::WriteAllText((Join-Path $DstMods 'mods.json'), "[`r`n" + ($json -join ",`r`n") + "`r`n]`r`n")

[IO.File]::WriteAllText((Join-Path $SrcWin64 'mirror_role.txt'), 'host')
[IO.File]::WriteAllText((Join-Path $DstWin64 'mirror_role.txt'), 'guest')
Write-Host "roles: host -> $SrcWin64\mirror_role.txt, guest -> $DstWin64\mirror_role.txt"

$HostSaves  = Join-Path $env:LOCALAPPDATA 'SurrounDead\Saved\SaveGames'
$GuestSaved = Join-Path $env:LOCALAPPDATA 'SurrounDead\Saved_Guest'
$GuestSaves = Join-Path $GuestSaved 'SaveGames'
if ($ReseedSaves -or -not (Test-Path $GuestSaves)) {
    New-Item -ItemType Directory -Force $GuestSaved | Out-Null
    if (Test-Path $GuestSaves) { Remove-Item $GuestSaves -Recurse -Force }
    Copy-Item $HostSaves $GuestSaves -Recurse
    Write-Host "guest saves seeded from $HostSaves"
}
foreach ($i in 1..8) { New-Item -ItemType Directory -Force (Join-Path $GuestSaves "SurrounSync_Session_$i") | Out-Null }
New-Item -ItemType Directory -Force (Join-Path (Split-Path $GuestSaves) 'SurrounSyncBackups') | Out-Null

$HostCfg = Join-Path $env:LOCALAPPDATA 'SurrounDead\Saved\Config'
$GuestCfg = Join-Path $GuestSaved 'Config'
if ((Test-Path $HostCfg) -and -not (Test-Path $GuestCfg)) { Copy-Item $HostCfg $GuestCfg -Recurse }

$size = (Get-ChildItem $DstWin64 -Recurse -File | Measure-Object Length -Sum).Sum / 1MB
Write-Host ("guest install ready at {0} ({1:N0} MB copied). Launch with tools\launch-guest.ps1" -f $Guest, $size)
